"""Runs every query in sql/queries.sql against data/shop.db and writes sql/results.md"""
import sqlite3, re, pandas as pd
text = open("sql/queries.sql").read()
blocks = re.split(r"\n(?=-- Q\d+:)", text)
con = sqlite3.connect("data/shop.db")
out = ["# Query results\n\nGenerated by `run_queries.py` from the synthetic dataset.\n"]
for b in blocks:
    m = re.match(r"-- (Q\d+): (.*)\n", b)
    if not m: continue
    df = pd.read_sql_query(b, con)
    for c in df.select_dtypes('float'):
        if (df[c].dropna() % 1 == 0).all(): df[c] = df[c].astype('Int64')
    out.append(f"\n## {m.group(1)}: {m.group(2)}\n\n" + df.to_markdown(index=False, floatfmt=",.2f", intfmt=",") + "\n")
open("sql/results.md","w").write("".join(out))
print("".join(out))
